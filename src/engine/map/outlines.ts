// Схематичні контури країн (довгота, широта). Намальовані вручну «з голови» —
// це не картографічні дані, а стилізація для гри. Спільні кордони задані дугами,
// щоб сусідні країни ділили точно ту саму лінію.

import type { Pt } from './geometry';

type LL = Array<[number, number]>;

const rev = (a: LL): LL => [...a].reverse() as LL;

/** З'єднати дуги в кільце, прибираючи дублікати стиків. */
function chain(...arcs: LL[]): LL {
  const out: LL = [];
  for (const arc of arcs) {
    for (const p of arc) {
      const last = out[out.length - 1];
      if (last && Math.abs(last[0] - p[0]) < 1e-9 && Math.abs(last[1] - p[1]) < 1e-9) continue;
      out.push(p);
    }
  }
  // замкнути без дубля першої точки
  const f = out[0];
  const l = out[out.length - 1];
  if (f && l && Math.abs(f[0] - l[0]) < 1e-9 && Math.abs(f[1] - l[1]) < 1e-9) out.pop();
  return out;
}

